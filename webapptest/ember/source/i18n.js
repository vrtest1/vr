export function detectLanguage(saved,browserLanguage){return Object.hasOwn(dictionaries,saved)?saved:(String(browserLanguage).toLowerCase().startsWith('ja')?'ja':'en');}
let saved;try{saved=localStorage.getItem('ember.language');}catch{}
export let language=detectLanguage(saved,globalThis.navigator?.languages?.[0]||globalThis.navigator?.language||'en');
export function t(key,params={}){const text=dictionaries[language][key]??dictionaries.en[key]??key;return text.replace(/\{(\w+)\}/g,(_,name)=>params[name]??'{'+name+'}');}
export function applyTranslations(){
 document.documentElement.lang=language;document.title=t('title');document.querySelector('meta[name="description"]')?.setAttribute('content',t('description'));
 document.querySelectorAll('[data-i18n]').forEach(el=>el.textContent=t(el.getAttribute('data-i18n')));
 for(const attribute of ['title','aria-label'])document.querySelectorAll('[data-i18n-'+attribute+']').forEach(el=>el.setAttribute(attribute,t(el.getAttribute('data-i18n-'+attribute))));
 document.querySelectorAll('[data-language]').forEach(el=>el.setAttribute('aria-pressed',String(el.dataset.language===language)));
}
export function setLanguage(next){if(!Object.hasOwn(dictionaries,next))return;language=next;try{localStorage.setItem('ember.language',language);}catch{}applyTranslations();window.dispatchEvent(new Event('ember-languagechange'));}
export function initI18n(){document.querySelectorAll('[data-language]').forEach(el=>el.addEventListener('click',()=>setLanguage(el.dataset.language)));applyTranslations();}
