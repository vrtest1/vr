// Japanese / English text. The language follows the browser (Japanese if it prefers Japanese, otherwise English)
// until the user picks one with the JP / EN switch; that choice is kept between visits.
export function initialLang(){
 try{const saved=localStorage.getItem('unitas.lang');if(saved==='ja'||saved==='en')return saved;}catch{}
 return (navigator.languages?.[0]||navigator.language||'').toLowerCase().startsWith('ja')?'ja':'en';
}
export function saveLang(lang){try{localStorage.setItem('unitas.lang',lang);}catch{}}

